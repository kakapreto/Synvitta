    source = str(text)
    translations = TRANSLATIONS if language == "en" else _REVERSE_TRANSLATIONS
    exact = translations.get(source)
    if exact is not None:
        return exact
    result = source
    for original in sorted(translations, key=len, reverse=True):
        if len(original) >= 16 and original in result:
            result = result.replace(original, translations[original])
    partial_translations = (
        _PARTIAL_TRANSLATIONS if language == "en" else _REVERSE_PARTIAL_TRANSLATIONS
    )
    for original, translated in partial_translations.items():
        result = result.replace(original, translated)
    return result
